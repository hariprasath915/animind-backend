def _detect_scene_count(question: str) -> int:
    """
    Returns 3, 4, or 5 — the number of animation scenes to generate.
    Decision is purely heuristic (regex + length), no AI call needed.
    """
    q   = question.strip()
    ql  = q.lower()
    length = len(q)

    # ── Hard 5-scene triggers ────────────────────────────────────────────────
    # JEE / NEET / board-exam markers
    jee_neet_kw = [
        "jee", "neet", "iit", "aieee", "cbse", "class 11", "class 12",
        "assertion", "reason", "statement-1", "statement-2",
        "column i", "column ii", "match the",
        "passage", "paragraph based",
    ]
    if any(k in ql for k in jee_neet_kw):
        return 5

    # Multi-part sub-question markers: (i), (ii), (a), (b), Part A, Q1, Q2 …
    subq_patterns = [
        r'\(\s*i+\s*\)',          # (i), (ii), (iii)
        r'\(\s*[a-d]\s*\)',       # (a), (b), (c), (d)
        r'\bpart\s+[a-d1-4]\b',  # Part A, Part 1
        r'\bq\s*[1-9]\b',        # Q1, Q2
        r'\(\s*[1-4]\s*\)',       # (1), (2)
    ]
    subq_count = sum(len(re.findall(p, ql)) for p in subq_patterns)
    if subq_count >= 2:
        return 5

    # Multi-step derivation / proof
    derive_kw = ["derive", "prove", "hence show", "show that", "obtain an expression"]
    if any(k in ql for k in derive_kw):
        return 5

    # Multiple "find / calculate / determine" clauses (≥ 2)
    find_count = len(re.findall(
        r'\b(?:find|calculate|determine|evaluate|compute|obtain)\b', ql))
    if find_count >= 2:
        return 5

    # Count distinct numeric given values
    num_count = len(re.findall(r'[-+]?\d+(?:\.\d+)?(?:\s*[×x]\s*10\^?[-+]?\d+)?', q))

    # Long question text (pasted full problem)
    if length >= 400:
        return 5

    if num_count >= 4:
        return 5

    # ── Medium 4-scene triggers ──────────────────────────────────────────────
    if length >= 200 or num_count >= 2 or find_count == 1:
        return 4

    # ── Default: simple / short → 3 scenes ──────────────────────────────────
    return 3


def _classify_topic(question):
    q = question.lower()
    scores = {
        "BIOLOGICAL":     sum(1 for k in ["cell","dna","rna","protein","photosynthesis","mitosis","enzyme","hormone","gene","organism","bacteria","virus","chromosome","metabolism"] if k in q),
        "MATHEMATICAL":   sum(1 for k in ["integral","derivative","matrix","vector","theorem","equation","polynomial","logarithm","trigonometry","calculus","function","graph","proof"] if k in q),
        "ABSTRACT":       sum(1 for k in ["philosophy","ethics","democracy","capitalism","justice","freedom","psychology","consciousness","society","ideology","culture","politics"] if k in q),
        "PROCESS_BASED":  sum(1 for k in ["how does","how do","step by step","process","algorithm","mechanism","workflow","procedure","stages","works","function","operation"] if k in q),
        "VISUAL_PHYSICS": sum(1 for k in ["force","velocity","acceleration","mass","energy","momentum","gravity","pressure","current","voltage","wave","circuit","newton","friction","torque","field","charge","resistance","heat","thermal","temperature","pipe","cylinder","conduction","convection","concentration","evaporation","mass transfer","diffusion"] if k in q),
    }
    max_score = max(scores.values())
    if max_score >= 2:
        top = [c for c, s in scores.items() if s == max_score]
        return top[0] if len(top) == 1 else "MIXED"
    if sum(1 for s in scores.values() if s > 0) >= 3:
        return "MIXED"
    try:
        resp = client.messages.create(
            model=Q_MODEL, max_tokens=30,
            system="Reply with ONLY one of: VISUAL_PHYSICS, PROCESS_BASED, MATHEMATICAL, BIOLOGICAL, ABSTRACT, MIXED",
            messages=[{"role": "user", "content": f"Classify: {question[:200]}"}])
        cat = resp.content[0].text.strip().upper()
        if cat in STRATEGY_TEMPLATES:
            return cat
    except Exception:
        pass
    return "PROCESS_BASED"


async def _classify_topic_async(question):
    """
    Async wrapper around _classify_topic(). The keyword scorer inside is
    instant, but its fallback path makes a blocking client.messages.create()
    call. Running that directly on the event loop would freeze the whole
    server for the duration of the call, so it's offloaded to a thread here
    -- same pattern used for every other AI call in this file.
    """
    return await asyncio.to_thread(_classify_topic, question)


