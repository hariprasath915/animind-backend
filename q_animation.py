#  MODULE 2.6 -- GivenValuesExtractor
#  NEW in v0.2: extracts numeric given values for the #given-strip cards
# ===========================================================================
class GivenValuesExtractor:
    """
    Extracts key given quantities from the question text and returns a list of
    dicts: {label, value, unit, color_class}
    color_class cycles through: gc-blue, gc-teal, gc-green, gc-amber
    Max 4 cards (to fill a 4-column grid nicely).
    """
    _COLOR_CLASSES = ["gc-blue", "gc-teal", "gc-green", "gc-amber"]

    # Matches patterns like:  "3.5 kg/m", "0.002 m/s", "250°C", "5 m²"
    _VALUE_RE = re.compile(
        r'(?P<val>[-+]?\d+(?:\.\d+)?(?:\s*[×x]\s*10\^?[-+]?\d+)?)'
        r'\s*(?P<unit>[A-Za-z°²³µ/%][A-Za-z°²³µ·/²³\s]*(?:/[A-Za-z²³]+)?)?',
        re.IGNORECASE
    )
    # Common label markers before values
    _LABEL_RE = re.compile(
        r'(?:'
        r'(?P<label>[A-Za-z_][A-Za-z_\s]{0,40}?)'  # multi-word label
        r'\s*(?:=|is|of|:)\s*'
        r'(?P<val>[-+]?\d+(?:\.\d+)?(?:\s*[×x]\s*10\^?[-+]?\d+)?)'
        r'\s*(?P<unit>[A-Za-z°²³µ/%][A-Za-z°²³µ·/²³\s]*(?:/[A-Za-z²³]+)?)?'
        r')',
        re.IGNORECASE
    )

    @classmethod
    def extract(cls, question):
        cards = []
        seen_vals = set()
        for m in cls._LABEL_RE.finditer(question):
            label = m.group("label").strip().rstrip(",:;")
            val   = m.group("val").strip()
            unit  = (m.group("unit") or "").strip().rstrip(".,;")
            key   = val + unit
            if key in seen_vals or not label or len(label) < 2:
                continue
            seen_vals.add(key)
            color = cls._COLOR_CLASSES[len(cards) % len(cls._COLOR_CLASSES)]
            cards.append({"label": label, "value": val, "unit": unit, "color": color})
            if len(cards) >= 4:
                break
        QAnimLogger.ok("GivenExtractor", f"Extracted {len(cards)} given card(s)")
        return cards


# ===========================================================================
#  MODULE 2.7 -- LargeInputPreprocessor
#  NEW in v0.3: compresses long questions before they hit the animation AI.
#
#  WHY THIS EXISTS
#  ---------------
#  Long JEE/NEET-style inputs (600+ chars) carry:
#    • Option lists  (A) ... (B) ... (C) ... (D) that the animators don't need
#    • Multi-paragraph context paragraphs that repeat the same physics setup
#    • Redundant given-value sentences already extracted by GivenValuesExtractor
#    • MCQ stems, column-matching tables, assertion-reason boilerplate
#  All of that pads the prompt without improving animation quality.  Worse, the
#  fatter prompt causes longer generation times → more likely to hit a timeout
#  → "Failed to Fetch" on the client side.
#
#  STRATEGY: STRUCTURED COMPRESSION via a fast Haiku call
#  -------------------------------------------------------
#  When input length exceeds COMPRESS_THRESHOLD characters we send the raw
#  question to claude-haiku-4-5 with a tight instruction to return ONLY a
#  compact structured block:
#
#      TOPIC: <one-line physics/math topic>
#      GIVEN: <comma-separated key values with units>
#      FIND: <what the question asks for>
#      CONTEXT: <one sentence of essential background, if any>
#      CORE_QUESTION: <the single cleanest sentence that states the problem>
#
#  This block is ≤ 300 chars and contains everything the animation AI needs.
#  No information loss on the critical facts; heavy noise is stripped.
#
#  FALLBACKS (layered, in order of preference)
#  -------------------------------------------
#  1. Haiku compression  (AI, accurate)
#  2. Heuristic truncation  (fast regex-based strip of MCQ options + trim)
#  3. Hard truncation to HARD_LIMIT chars  (last resort, never crashes)
#
#  The original raw question is ALWAYS kept on the result object so that
#  GivenValuesExtractor and ToFindExtractor (which run on the raw text) are
#  unaffected.  Only the AI generation stages receive the compressed form.
# ===========================================================================

class LargeInputPreprocessor:
    """
    Transparently compresses questions that exceed COMPRESS_THRESHOLD before
    they are sent to the main animation AI stages.

    Usage:
        compressed = LargeInputPreprocessor.compress(raw_question)
        # compressed == raw_question  if it was short enough
        # compressed == structured summary  if it was too long
    """

    # Characters above which we attempt compression
    COMPRESS_THRESHOLD = 600
    # Absolute hard-limit (safety net — never pass more than this to any AI)
    HARD_LIMIT = 2000

    # Regex to strip MCQ options  — matches lines like:
    #   (A) option text    (B) option text …
    #   A. option          B. option …
    #   Option 1: …        Option 2: …
    _MCQ_LINE_RE = re.compile(
        r'^\s*(?:\([A-Da-d1-4]\)|[A-Da-d1-4][.)]\s|Option\s*[A-D1-4]\s*[:.])',
        re.MULTILINE,
    )
    # Assertion-Reason / Column-matching boilerplate headers
    _BOILERPLATE_RE = re.compile(
        r'(?:STATEMENT\s*[–\-:]\s*[12]|ASSERTION\s*[–\-:]\s*|REASON\s*[–\-:]\s*|'
        r'Column\s*[I12]\s*[–\-:]\s*|Match\s+the\s+following)',
        re.IGNORECASE,
    )

    # ── Haiku compression prompt ────────────────────────────────────────────
    _COMPRESS_SYSTEM = (
        "You are a concise exam-question compressor. "
        "Return ONLY the structured block below with no preamble or trailing text:\n\n"
        "TOPIC: <one-line subject area>\n"
        "GIVEN: <comma-separated key quantities with values and units>\n"
        "FIND: <exactly what the question asks us to compute or determine>\n"
        "CONTEXT: <one sentence of essential background, or NONE>\n"
        "CORE_QUESTION: <the single clearest restatement of the problem in ≤ 30 words>\n\n"
        "Rules: every line must be present. Be precise with numbers and units. "
        "Never omit a given value. Never add anything outside the five fields."
    )

    @classmethod
    def needs_compression(cls, question: str) -> bool:
        return len(question) > cls.COMPRESS_THRESHOLD

    @classmethod
    def compress(cls, question: str) -> str:
        """
        Return a compressed representation of *question* suitable for the
        animation AI.  The return value is always a non-empty string.

        Compression path:
            1. If short enough → return as-is.
            2. Try Haiku AI compression → use if it produces a valid block.
            3. Fall back to heuristic stripping (MCQ options, boilerplate).
            4. Hard-truncate to HARD_LIMIT as a final safety net.
        """
        if not cls.needs_compression(question):
            return question

        short_q = question[:80] + ("…" if len(question) > 80 else "")
        QAnimLogger.info(
            "LargeInputPreprocessor",
            f"Input length={len(question)} exceeds threshold={cls.COMPRESS_THRESHOLD} — compressing…"
            f"  ('{short_q}')"
        )

        # ── Attempt 1: Haiku AI compression ─────────────────────────────────
        try:
            compressed = cls._haiku_compress(question)
            if compressed:
                QAnimLogger.ok(
                    "LargeInputPreprocessor",
                    f"Haiku compression OK: {len(question)} → {len(compressed)} chars"
                )
                return compressed
        except Exception as exc:
            QAnimLogger.warn("LargeInputPreprocessor", f"Haiku compression failed: {exc}")

        # ── Attempt 2: Heuristic strip ────────────────────────────────────
        try:
            stripped = cls._heuristic_strip(question)
            if stripped and len(stripped) < len(question):
                QAnimLogger.ok(
                    "LargeInputPreprocessor",
                    f"Heuristic strip OK: {len(question)} → {len(stripped)} chars"
                )
                return stripped[:cls.HARD_LIMIT]
        except Exception as exc:
            QAnimLogger.warn("LargeInputPreprocessor", f"Heuristic strip failed: {exc}")

        # ── Attempt 3: Hard truncation ────────────────────────────────────
        QAnimLogger.warn(
            "LargeInputPreprocessor",
            f"Falling back to hard truncation → {cls.HARD_LIMIT} chars"
        )
        return question[:cls.HARD_LIMIT]

    # ── Private helpers ─────────────────────────────────────────────────────

    @classmethod
    def _haiku_compress(cls, question: str) -> Optional[str]:
        """
        Use claude-haiku-4-5 to produce a structured 5-field summary block.
        Raises on API error so callers can fall through to heuristics.
        """
        # Feed at most HARD_LIMIT chars to Haiku itself (prevents mega-inputs)
        safe_input = question[:cls.HARD_LIMIT]
        msg = client.messages.create(
            model="claude-haiku-4-5",
            max_tokens=400,
            system=cls._COMPRESS_SYSTEM,
            messages=[{"role": "user", "content": safe_input}],
        )
        raw = msg.content[0].text.strip()

        # Validate: all 5 fields must be present
        required = ["TOPIC:", "GIVEN:", "FIND:", "CONTEXT:", "CORE_QUESTION:"]
        if all(f in raw for f in required):
            return raw
        # Partial result — still usable if it has CORE_QUESTION
        if "CORE_QUESTION:" in raw:
            QAnimLogger.warn("LargeInputPreprocessor", "Haiku block partial — using anyway")
            return raw
        QAnimLogger.warn("LargeInputPreprocessor", f"Haiku block malformed — ignoring. raw={raw[:120]!r}")
        return None

    @classmethod
    def _heuristic_strip(cls, question: str) -> str:
        """
        Fast regex-based stripping:
          1. Remove MCQ option lines.
          2. Remove assertion/reason/column-matching header lines.
          3. Collapse multiple blank lines.
          4. Strip surrounding whitespace.
        Does NOT use any AI.
        """
        text = question

        # Remove option lines
        # Find first MCQ option match; strip from there to end of options block
        mcq_match = cls._MCQ_LINE_RE.search(text)
        if mcq_match:
            # Keep everything before the first option line (the stem)
            stem = text[:mcq_match.start()].strip()
            if len(stem) > 80:  # stem is substantive
                text = stem
            else:
                # Short stem — remove just the option lines, keep rest
                text = cls._MCQ_LINE_RE.sub("", text)

        # Remove boilerplate headers
        text = cls._BOILERPLATE_RE.sub("", text)

        # Collapse blank lines
        text = re.sub(r'\n{3,}', '\n\n', text).strip()

        return text


# ===========================================================================
#  MODULE 2.8 -- SmartPromptBuilder
#  NEW in v0.4: Analyses the compressed question and builds a rich, structured
#  prompt block so the animation AI receives maximum signal for complex inputs.
#
#  WHY THIS EXISTS
#  ---------------
#  LargeInputPreprocessor (Module 2.7) shrinks long questions so they fit in
#  the prompt without bloat.  But it only compresses — it does NOT analyse
#  whether the underlying question is conceptually complex (multi-formula,
#  multi-domain, multi-part, derivation-heavy, etc.).
#
#  When the AI receives a short compressed block without any complexity signal,
#  it may produce a shallow or incomplete animation — acceptable for a simple
#  plug-in question, but wrong for a hard JEE-style problem that genuinely
#  needs every scene to show a different formula/stage.
#
#  SmartPromptBuilder bridges that gap:
#    1. Analyses the (compressed) question with a fast Haiku call.
#    2. Produces a PROMPT_ENRICHMENT block:
#         - COMPLEXITY_TIER: simple | medium | complex | multi_part
#         - KEY_CONCEPTS: comma-separated list of concepts / formulas needed
#         - SCENE_SUGGESTIONS: one sentence per scene (hint, not a mandate)
#         - SPECIAL_NOTES: any edge cases the animation AI must handle
#    3. Injects this block into the user-content of both the solution AI
#       and the concept AI, without touching the (cached) system prompt.
#
#  For short / simple questions the enrichment is a no-op (returns "").
#  For complex questions it adds ≈ 120 extra tokens of signal that dramatically
#  improves the animation quality and accuracy without increasing latency
#  (the Haiku call runs concurrently with the LargeInputPreprocessor stage).
# ===========================================================================

class SmartPromptBuilder:
    """
    Analyses the question (post-compression) and produces a structured
    PROMPT_ENRICHMENT block that is appended to the animation AI user prompt.

    The enrichment is:
        - A no-op (empty string) for simple/short questions
        - A rich multi-field block for medium / complex / multi-part questions
    """

    # Only enrich when there is real complexity (saves Haiku cost for trivials)
    _ENRICH_THRESHOLD = 120   # chars; below this the question is almost certainly simple

    # Complexity signals that warrant enrichment even if the text is short
    _COMPLEX_KW = [
        "derive", "prove", "show that", "hence show", "obtain an expression",
        "multi-part", "part (a)", "part (b)", "(i)", "(ii)",
        "assertion", "reason", "match the", "column i", "column ii",
        "two or more", "and also find", "also determine", "also calculate",
        "jee", "neet", "iit", "aieee", "cbse",
    ]

    _ENRICH_SYSTEM = (
        "You are an expert educational content analyst. "
        "Analyse the student question below and return ONLY the structured block shown — "
        "no preamble, no trailing text, no JSON, no markdown:\n\n"
        "COMPLEXITY_TIER: <one of: simple | medium | complex | multi_part>\n"
        "KEY_CONCEPTS: <comma-separated list of the 2-5 main formulas, laws, or concepts needed>\n"
        "SCENE_SUGGESTIONS: <exactly N comma-separated one-sentence hints, one per animation scene; "
        "N will be provided in the user message>\n"
        "SPECIAL_NOTES: <one sentence about the trickiest part, or NONE>\n\n"
        "Rules:\n"
        "- Every field must be present.\n"
        "- KEY_CONCEPTS: name the actual formulas/laws (e.g. 'Fourier heat law', 'Newton 2nd law').\n"
        "- SCENE_SUGGESTIONS: each hint describes what ONE scene should visualise — "
        "keep it short (≤ 15 words) and specific to THIS question.\n"
        "- SPECIAL_NOTES: flag multi-unit conversions, tricky sign conventions, "
        "ambiguous notation, or multi-quantity outputs. Write NONE if there is nothing special.\n"
        "- Do NOT solve the problem or give numerical answers."
    )

    @classmethod
    def _should_enrich(cls, question: str) -> bool:
        """Return True when the question warrants enrichment analysis."""
        if len(question) >= cls._ENRICH_THRESHOLD:
            return True
        ql = question.lower()
        return any(k in ql for k in cls._COMPLEX_KW)

    @classmethod
    def build(cls, question: str, n_scenes: int) -> str:
        """
        Synchronous entry point.

        Args:
            question: The (possibly compressed) question text.
            n_scenes: Number of animation scenes to generate (3 / 4 / 5).

        Returns:
            A multi-line PROMPT_ENRICHMENT string to append to the AI user
            prompt, or an empty string for simple inputs.
        """
        if not cls._should_enrich(question):
            QAnimLogger.info("SmartPromptBuilder", "Short/simple question — skipping enrichment")
            return ""

        QAnimLogger.info(
            "SmartPromptBuilder",
            f"Enriching prompt for {len(question)}-char question (n_scenes={n_scenes})..."
        )
        try:
            enrichment = cls._haiku_analyse(question, n_scenes)
            if enrichment:
                QAnimLogger.ok(
                    "SmartPromptBuilder",
                    f"Enrichment OK ({len(enrichment)} chars)"
                )
                return enrichment
        except Exception as exc:
            QAnimLogger.warn("SmartPromptBuilder", f"Enrichment failed: {exc} — using plain prompt")
        return ""

    @classmethod
    async def build_async(cls, question: str, n_scenes: int) -> str:
        """Async wrapper so the enrichment call runs concurrently in the pipeline."""
        loop = asyncio.get_event_loop()
        return await loop.run_in_executor(None, cls.build, question, n_scenes)

    # ── Private helpers ──────────────────────────────────────────────────────

    @classmethod
    def _haiku_analyse(cls, question: str, n_scenes: int) -> str:
        """
        Use claude-haiku-4-5 to produce the enrichment block.
        Sends at most 1 200 chars of the question to keep the call fast.
        """
        safe_q = question[:1200]
        user_msg = (
            f"Analyse this question. "
            f"Produce SCENE_SUGGESTIONS with exactly {n_scenes} comma-separated hints "
            f"(one per animation scene).\n\n"
            f"QUESTION:\n{safe_q}"
        )
        msg = client.messages.create(
            model=HAIKU_SOLUTION_MODEL,
            max_tokens=350,
            system=[{
                "type": "text",
                "text": cls._ENRICH_SYSTEM,
                "cache_control": {"type": "ephemeral"},
            }],
            messages=[{"role": "user", "content": user_msg}],
        )
        raw = msg.content[0].text.strip()

        # Validate: at least COMPLEXITY_TIER and KEY_CONCEPTS must be present
        required = ["COMPLEXITY_TIER:", "KEY_CONCEPTS:"]
        if not all(f in raw for f in required):
            QAnimLogger.warn(
                "SmartPromptBuilder",
                f"Enrichment block malformed — ignoring. preview={raw[:100]!r}"
            )
            return ""

        return (
            "\n\n═══ QUESTION ANALYSIS (generated by SmartPromptBuilder) ═══\n"
            + raw
            + "\n═══ END ANALYSIS ═══\n"
        )


# ===========================================================================
#  MODULE 3 -- HtmlSanitizer
# ===========================================================================
class HtmlSanitizer:

    @classmethod
    def sanitize(cls, html):
        html = html.replace('\ufeff', '')
        end = html.rfind('</html>')
        if end != -1:
            html = html[:end + 7]
        html = re.sub(r'document\.write\s*\([^)]*\)\s*;?', '', html, flags=re.IGNORECASE)
        html = re.sub(
            r'<script[^>]+src\s*=\s*["\'][^"\']*["\'][^>]*>\s*</script>',
            '', html, flags=re.IGNORECASE | re.DOTALL)
        html = cls._fix_template_literals(html)
        html = cls._fix_unescaped_string_newlines(html)
        html = cls._fix_const_let(html)
        html = cls._fix_arrow_functions(html)
        html = cls._fix_single_quote_apostrophes(html)
        html = cls._wrap_scripts_in_error_boundary(html)
        html = re.sub(r'<svg(?![^>]*xmlns)', '<svg xmlns="http://www.w3.org/2000/svg"', html, flags=re.IGNORECASE)
        html = cls._fix_svg_subscripts(html)
        html = html.replace('\x00', '')
        QAnimLogger.ok("Sanitizer", "HTML sanitized")
        return html

    _SUB_PATTERN = re.compile(
        r'(?<![A-Za-z\u03b1-\u03c9\u0391-\u03a9\d])'
        r'([A-Za-z\u03b1-\u03c9\u0391-\u03a9\d])'
        r'_'
        r'(?:'
        r'\{([^}]{1,20})\}'
        r'|([A-Za-z\u03b1-\u03c9\u0391-\u03a9\d]+)'
        r')'
    )

    @classmethod
    def _replace_sub_in_text_content(cls, content):
        def replacer(m):
            base = m.group(1)
            sub  = m.group(2) if m.group(2) else m.group(3)
            return (base
                    + '<tspan dy="5" font-size="0.72em">' + sub + '</tspan>'
                    + '<tspan dy="-5" font-size="1em"></tspan>')
        return cls._SUB_PATTERN.sub(replacer, content)

    @classmethod
    def _fix_svg_subscripts(cls, html):
        def fix_svg_block(svg_match):
            svg_content = svg_match.group(0)
            def fix_text_tag(t_match):
                full   = t_match.group(0)
                open_t = t_match.group(1)
                inner  = t_match.group(2)
                close_t= t_match.group(3)
                if 'dy=' in inner and 'font-size' in inner:
                    return full
                if '_' not in inner:
                    return full
                fixed = cls._replace_sub_in_text_content(inner)
                if fixed != inner:
                    QAnimLogger.info("Sanitizer", f"Subscript fixed in <text>: {inner[:60]!r}")
                return open_t + fixed + close_t
            svg_content = re.sub(
                r'(<text\b[^>]*>)(.*?)(</text>)',
                fix_text_tag, svg_content, flags=re.DOTALL | re.IGNORECASE)
            return svg_content
        html = re.sub(r'<svg[\s\S]*?</svg>', fix_svg_block, html, flags=re.IGNORECASE)
        return html

    @classmethod
    def _wrap_scripts_in_error_boundary(cls, html):
        def wrap_script(match):
            tag, body, close = match.group(1), match.group(2), match.group(3)
            if re.search(r'type\s*=\s*["\']application/', tag, re.IGNORECASE):
                return match.group(0)
            stripped = body.strip()
            if stripped.startswith('try {') or stripped.startswith('try{'):
                return match.group(0)
            if len(stripped) < 20:
                return match.group(0)
            wrapped = (
                "\n/* -- QAnim Error Boundary -- */\ntry {\n" + body +
                "\n} catch (_qanim_err) {\n"
                "  /* Log silently; do NOT surface the error modal to users. */\n"
                "  console.error('[QAnim ErrorBoundary]', _qanim_err);\n"
                "}\n")
            return f"{tag}{wrapped}{close}"
        return re.sub(r'(<script(?:\s[^>]*)?>)(.*?)(</script>)', wrap_script, html, flags=re.DOTALL | re.IGNORECASE)

    @classmethod
    def _fix_template_literals(cls, html):
        def process_script(script_match):
            tag, body, close = script_match.group(1), script_match.group(2), script_match.group(3)
            if re.search(r'type\s*=\s*["\']application/', tag, re.IGNORECASE):
                return script_match.group(0)
            def replace_template(m):
                raw = m.group(1)
                parts = re.split(r'\$\{([^}]*)\}', raw)
                out = []
                for idx, part in enumerate(parts):
                    if idx % 2 == 0:
                        esc = part.replace('\\','\\\\').replace('"','\\"').replace('\n','\\n').replace('\r','\\r').replace('\t','\\t')
                        out.append('"' + esc + '"')
                    else:
                        out.append('(' + part.strip() + ')')
                while out and out[0]  == '""': out.pop(0)
                while out and out[-1] == '""': out.pop()
                return (' + '.join(out)) if out else '""'
            original = body
            body = re.sub(r'`((?:[^`\\]|\\.)*)`', replace_template, body, flags=re.DOTALL)
            if body != original:
                QAnimLogger.warn("Sanitizer", "Backtick template literals replaced")
            return f"{tag}{body}{close}"
        return re.sub(r'(<script(?:\s[^>]*)?>)(.*?)(</script>)', process_script, html, flags=re.DOTALL | re.IGNORECASE)

    @classmethod
    def _fix_unescaped_string_newlines(cls, html):
        """
        Fix a common AI-generation mistake: a single/double-quoted JS string
        literal (e.g. inside a JSON array like `var scenes = [{"desc": "...`)
        that contains a LITERAL raw newline / carriage-return / tab character
        instead of an escaped \\n / \\r / \\t. A raw newline inside a quoted
        JS string is invalid syntax and produces:
            Uncaught SyntaxError: Invalid or unexpected token
        This scans every <script> block, finds quoted string literals
        (single or double quotes, respecting existing escapes), and replaces
        any raw control characters found INSIDE them with their escaped
        equivalents -- without touching anything outside string literals
        (so normal multi-line code formatting is left alone).
        """
        STRING_RE = re.compile(r'(["\'])((?:\\.|(?!\1).)*)\1', re.DOTALL)

        def fix_str(sm):
            quote, inner = sm.group(1), sm.group(2)
            fixed = (inner.replace('\r\n', '\\n')
                           .replace('\n', '\\n')
                           .replace('\r', '\\n')
                           .replace('\t', '\\t'))
            return quote + fixed + quote

        def process_script(m):
            tag, body, close = m.group(1), m.group(2), m.group(3)
            fixed_body = STRING_RE.sub(fix_str, body)
            if fixed_body != body:
                QAnimLogger.warn("Sanitizer", "Raw newline/tab found inside a JS string literal -- escaped")
            return f"{tag}{fixed_body}{close}"

        return re.sub(r'(<script(?:\s[^>]*)?>)(.*?)(</script>)', process_script, html, flags=re.DOTALL | re.IGNORECASE)

    @classmethod
    def _fix_const_let(cls, html):
        def process_script(m):
            tag, body, close = m.group(1), m.group(2), m.group(3)
            if re.search(r'type\s*=\s*["\']application/', tag, re.IGNORECASE):
                return m.group(0)
            body = re.sub(r'\bconst\b', 'var', body)
            body = re.sub(r'\blet\b',   'var', body)
            return f"{tag}{body}{close}"
        return re.sub(r'(<script(?:\s[^>]*)?>)(.*?)(</script>)', process_script, html, flags=re.DOTALL | re.IGNORECASE)

    @classmethod
    def _fix_arrow_functions(cls, html):
        def process_script(m):
            tag, body, close = m.group(1), m.group(2), m.group(3)
            if re.search(r'type\s*=\s*["\']application/', tag, re.IGNORECASE):
                return m.group(0)
            body = re.sub(r'\(([^)]*)\)\s*=>\s*(\{)', r'function(\1) \2', body)
            body = re.sub(r'\(([^)]*)\)\s*=>\s*([^{;\n][^;\n]*)', r'function(\1) { return \2; }', body)
            body = re.sub(r'(?<![\w$])([A-Za-z_$][\w$]*)\s*=>\s*(\{)', r'function(\1) \2', body)
            body = re.sub(r'(?<![\w$])([A-Za-z_$][\w$]*)\s*=>\s*([^{;\n][^;\n]*)', r'function(\1) { return \2; }', body)
            return f"{tag}{body}{close}"
        return re.sub(r'(<script(?:\s[^>]*)?>)(.*?)(</script>)', process_script, html, flags=re.DOTALL | re.IGNORECASE)

    @classmethod
    def _fix_single_quote_apostrophes(cls, html):
        def process_script(m):
            tag, body, close = m.group(1), m.group(2), m.group(3)
            if re.search(r'type\s*=\s*["\']application/', tag, re.IGNORECASE):
                return m.group(0)
            def fix_sq_string(mm):
                inner = mm.group(1)
                if re.search(r"(?<!\\)'", inner):
                    fixed = inner.replace("\\'", "'").replace('"', '\\"')
                    return '"' + fixed + '"'
                return mm.group(0)
            body = re.sub(r"'((?:[^'\\\n]|\\.)*)'", fix_sq_string, body)
            return f"{tag}{body}{close}"
        return re.sub(r'(<script(?:\s[^>]*)?>)(.*?)(</script>)', process_script, html, flags=re.DOTALL | re.IGNORECASE)


