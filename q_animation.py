async def _generate_concept_animation(question, category, n_scenes: int = 5, enrichment: str = ""):
    """Stage 1 -- Concept animation (n_scenes scenes, light theme, no answer)."""
    QAnimLogger.info("ConceptPipeline", f"START  category={category}  n_scenes={n_scenes}")
    system_blocks, user_content = _build_concept_prompt(question, category, n_scenes, enrichment)
    try:
        # Offloaded to a thread: client.messages.create() is a blocking sync
        # call. Left un-offloaded, it freezes the entire asyncio event loop
        # for the whole duration of this Sonnet call (often 30-60s+ for
        # complex questions) -- which stalls every other request the server
        # is handling and can look like the server hung, producing
        # "Failed to fetch" on the frontend. This was also silently
        # cancelling the intended concurrency with the Solution AI call,
        # since two blocking calls can't actually run in parallel on one
        # event loop no matter how they're scheduled.
        msg = await asyncio.to_thread(
            client.messages.create,
            model=CONCEPT_MODEL, max_tokens=MAX_TOK_CONCEPT,
            system=system_blocks,
            messages=[{"role": "user", "content": user_content}])
        raw = msg.content[0].text.strip()
        QAnimLogger.info(
            "ConceptAI",
            f"model={CONCEPT_MODEL}  stop_reason={msg.stop_reason}  len={len(raw)}"
            f"  cache_read={getattr(msg.usage, 'cache_read_input_tokens', 0)}"
            f"  cache_create={getattr(msg.usage, 'cache_creation_input_tokens', 0)}"
        )
        if msg.stop_reason == "max_tokens":
            QAnimLogger.warn("ConceptAI", "Hit max_tokens -- may be truncated!")
    except Exception as e:
        QAnimLogger.error("ConceptAI", f"API call failed: {e}")
        return RecoveryEngine.fallback_html(question, f"Concept AI error: {e}")

    raw_for_concept = raw.replace('"concept_code"', '"animation_code"')
    parsed_c = _parse_response(raw_for_concept, question)
    concept_html = parsed_c.get("animation_code", "").strip()

    if not concept_html:
        for marker in ['<!DOCTYPE html>', '<html', '<svg']:
            idx = raw.find(marker)
            if idx != -1:
                end = raw.rfind('</html>')
                concept_html = raw[idx:end + 7] if end != -1 else raw[idx:]
                break

    if not concept_html:
        return RecoveryEngine.fallback_html(question, "Concept parse failed")

    try:
        GenerationValidator.validate(concept_html, require_svg=True)
    except ValidationError as e:
        QAnimLogger.warn("ConceptValidator", f"Validation failed: {e}")
        if '<svg' in concept_html and len(concept_html) > 200:
            concept_html = RecoveryEngine.partial_html(question, concept_html)
        else:
            return RecoveryEngine.fallback_html(question, str(e))

    # Concept animation: inject panels into the raw AI HTML (not page-wrapped)
    concept_html = HtmlSanitizer.sanitize(concept_html)
    concept_html = inject_notes_system(concept_html)
    concept_html = inject_teacher_voice(concept_html)
    concept_html = inject_step_controller(concept_html)  # LAST

    QAnimLogger.ok("ConceptPipeline", f"DONE -- len={len(concept_html):,}")
    return concept_html


async def generate_question_animation(question):
    """
    Public entry point. This is now a thin SAFETY-NET wrapper around the
    real pipeline (_run_generation_pipeline below).

    WHY: long or tough questions (large pasted text, multi-part JEE/NEET
    problems, etc.) are exactly the kind of input most likely to trip an
    edge case somewhere deep in this 4000+ line pipeline (a regex on an
    unusually large string, a malformed/truncated AI response, a missing
    field, etc.). Previously, ANY such error would raise all the way out
    of this function uncaught -- which crashes the request and is exactly
    what shows up to the user as "failed to fetch" (the server has no
    valid response to send back). Now, no matter what goes wrong inside
    the pipeline, this wrapper guarantees a normal, renderable result is
    always returned, so every kind of question -- short, long, easy, or
    hard -- produces an output instead of a hard failure.
    """
    question = (question or "").strip()
    if not question:
        raise ValueError("Question cannot be empty")
    try:
        return await _run_generation_pipeline(question)
    except Exception as e:
        QAnimLogger.error("Pipeline", f"UNHANDLED error -- falling back gracefully: {e}")
        return _build_failure_result(question, f"Unexpected error: {e}")


async def _run_generation_pipeline(question):
    """
    PIPELINE v0.2:

    Stage -1  -- LargeInputPreprocessor  (sync; fires only when len > threshold)
    Stage 0   -- ToFind + GivenValues Extraction  (sync, no AI, uses RAW question)
    Stage 0.5 -- SimpleMethodAnalyzer             (claude-haiku-4-5, concurrent)
    Stage 0.6 -- GlossaryAnalyzer (difficult-words) (claude-haiku-4-5, concurrent)
    Stage 1   -- Concept Animation   (claude-sonnet-4-6, uses COMPRESSED question)
    Stage 2   -- Solution Animation  (claude-sonnet-4-6, uses COMPRESSED question)
    Stage 3   -- Haiku Solution      (claude-haiku-4-5,  uses COMPRESSED question)
               [Stages 0.5, 0.6, 1, 2, 3 concurrent via asyncio.gather]

    Post-processing builds the full v0.2 page layout from the AI SVG.

    NOTE: this function is free to raise -- generate_question_animation()
    above catches everything and converts it into a graceful fallback.
    """
    short_q = question[:80] + ("..." if len(question) > 80 else "")
    QAnimLogger.info("Pipeline", f"START v0.2 -- '{short_q}'")

    # ── Stage -1: Large-input preprocessing ─────────────────────────────────
    # ai_question is what every AI stage receives.  It equals `question` when
    # input is short, or a compact structured block when it is long.
    # Stage 0 regex extractors always run on the original raw text.
    try:
        ai_question = LargeInputPreprocessor.compress(question)
    except Exception as _pre_exc:
        QAnimLogger.warn("Pipeline", f"Preprocessor raised unexpectedly: {_pre_exc} -- using raw")
        ai_question = question[:LargeInputPreprocessor.HARD_LIMIT]

    if ai_question != question:
        QAnimLogger.info(
            "Pipeline",
            f"Large-input compression active: raw={len(question)} -> ai={len(ai_question)} chars"
        )

    # Stage 0: Sync extraction -- always on the ORIGINAL raw question so that
    # GivenValuesExtractor and ToFindExtractor see full numeric text.
    to_find_targets = ToFindExtractor.extract(question)
    given_cards     = GivenValuesExtractor.extract(question)
    QAnimLogger.info("Pipeline", f"ToFind: {to_find_targets}")
    QAnimLogger.info("Pipeline", f"GivenCards: {len(given_cards)} card(s)")

    category = await _classify_topic_async(ai_question)
    QAnimLogger.info("Classifier", f"Category: {category}")

    # ── Scene count: heuristic detector (no extra AI call) ──────────────────
    n_scenes = _detect_scene_count(question)   # uses RAW question for best signal
    QAnimLogger.info("SceneCount", f"n_scenes={n_scenes} (raw_len={len(question)} ai_len={len(ai_question)})")

    # ── Stage 0.5 + 1 + 2 + 3: all concurrent ──────────────────────────────
    # SimpleMethodAnalyzer runs alongside the heavy AI stages at zero extra
    # wall-clock cost.  Its result is used to steer Stages 2 and 3.
    # All AI stages use ai_question (compressed when long, raw otherwise).

    async def _run_simple_analyzer():
        return await SimpleMethodAnalyzer.analyze_async(ai_question)

    # We run the simple-method analysis together with concept + solution + haiku.
    # Solution AI and Haiku must wait for the simple-method result, so we split
    # into two gather calls:
    #   gather_a: [concept_anim, simple_analysis]   (independent)
    #   gather_b: [solution_ai, haiku]               (depend on simple hint)
    # Both gather calls run concurrently relative to each other via a wrapper.

    # ── Stage -0.5: SmartPromptBuilder enrichment (concurrent with other pre-stages) ──
    # Runs the enrichment analysis asynchronously so it adds zero latency to the
    # critical path. The result is threaded into _build_prompt and
    # _build_concept_prompt as an extra user-content block.

    async def _run_smart_prompt_builder():
        return await SmartPromptBuilder.build_async(ai_question, n_scenes)

    async def _run_all_stages():
        # ── Sub-stage A: run SmartPromptBuilder + SimpleMethodAnalyzer + Gemini Scene 0 in parallel ──
        # Gemini is now a PRIMARY generator — it runs here alongside the fast
        # analysers, BEFORE Claude starts. Claude's prompt is built AFTER Gemini
        # finishes so it receives the real scene-0 SVG and is told not to generate it.
        analyzer_fut   = asyncio.ensure_future(_run_simple_analyzer())
        enrichment_fut = asyncio.ensure_future(_run_smart_prompt_builder())
        glossary_fut   = asyncio.ensure_future(GlossaryAnalyzer.analyze_async(ai_question))
        QAnimLogger.info("Gemini", "Gemini Scene 0 starting as PRIMARY generator (before Claude)...")
        gemini_fut     = asyncio.ensure_future(
            GeminiScene1Generator.generate_async(ai_question, category, n_scenes)
        )

        # Wait for all four pre-stage tasks to complete
        simple_result, enrichment, glossary_result, (gemini_scene0_group, gemini_animate0_fn) = await asyncio.gather(
            analyzer_fut, enrichment_fut, glossary_fut, gemini_fut
        )
        QAnimLogger.info("Pipeline", f"Glossary done: {len(glossary_result.get('terms', []))} term(s)")
        QAnimLogger.info("Pipeline", f"SimpleMethod done: use_simple={simple_result['use_simple']}")
        QAnimLogger.info("Pipeline", f"SmartPromptBuilder done: enrichment_len={len(enrichment)}")
        if gemini_scene0_group:
            QAnimLogger.ok("Gemini", f"Scene 0 PRIMARY generation done: svg_len={len(gemini_scene0_group)}, js_len={len(gemini_animate0_fn)}")
        else:
            QAnimLogger.warn("Gemini", "Scene 0 primary generation failed -- Claude will generate all scenes")

        # Build hints from analysis
        haiku_hint = SimpleMethodAnalyzer.build_haiku_hint(simple_result)
        sol_hint   = SimpleMethodAnalyzer.build_solution_hint(simple_result)

        # ── Sub-stage B: launch Claude stages with Gemini scene-0 already known ──
        # If Gemini succeeded, Claude's prompt includes the scene-0 SVG verbatim
        # and Claude only generates scenes 1..N-1.
        # If Gemini failed, gemini_scene0_group is "" and Claude generates all scenes.
        _sys_blocks, _user_content = _build_prompt(
            ai_question, category, n_scenes, enrichment,
            gemini_scene0_svg=gemini_scene0_group   # "" if Gemini failed
        )
        enriched_user_content = _user_content + sol_hint if sol_hint else _user_content

        async def _run_solution_ai():
            try:
                # Offloaded to a thread for the same reason as the Concept
                # AI call above -- this is the heaviest call in the whole
                # pipeline (full solution page HTML/SVG/JS), so leaving it
                # blocking the event loop is the single biggest contributor
                # to long, server-freezing requests on hard questions.
                msg = await asyncio.to_thread(
                    client.messages.create,
                    model=SOLUTION_MODEL, max_tokens=MAX_TOK,
                    system=_sys_blocks,
                    messages=[{"role": "user", "content": enriched_user_content}])
                raw = msg.content[0].text.strip()
                QAnimLogger.info(
                    "SolutionAI",
                    f"model={SOLUTION_MODEL}  stop_reason={msg.stop_reason}  len={len(raw)}"
                    f"  cache_read={getattr(msg.usage, 'cache_read_input_tokens', 0)}"
                    f"  cache_create={getattr(msg.usage, 'cache_creation_input_tokens', 0)}"
                )
                if msg.stop_reason == "max_tokens":
                    QAnimLogger.warn("SolutionAI", "Hit max_tokens -- may be truncated!")
                return raw
            except Exception as e:
                QAnimLogger.error("SolutionAI", f"API failed: {e}")
                raise

        # Concept animation also receives enrichment so its scene suggestions match
        concept_fut = asyncio.ensure_future(
            _generate_concept_animation(ai_question, category, n_scenes, enrichment)
        )

        # Solution AI + Haiku run concurrently
        sol_raw, haiku_sol = await asyncio.gather(
            _run_solution_ai(),
            HaikuSolutionGenerator.generate_async(ai_question, haiku_hint),
        )

        # Wait for concept (may already be done)
        concept_html = await concept_fut

        return concept_html, sol_raw, haiku_sol, simple_result, glossary_result, gemini_scene0_group, gemini_animate0_fn

    QAnimLogger.info("Pipeline", "Launching concurrent AI stages (0.5 + 1 + 2 + 3)...")
    try:
        concept_html, sol_raw, haiku_sol, simple_result, glossary_result, gemini_scene0_group, gemini_animate0_fn = await _run_all_stages()
    except Exception as e:
        QAnimLogger.error("Pipeline", f"Concurrent generation failed: {e}")
        return _build_failure_result(question, f"API error: {e}")

    # Parse solution animation
    result = _parse_response(sol_raw, question)
    result["category"]               = category
    result["n_scenes"]               = n_scenes
    result["engine_version"]         = "v0.6"
    result["concept_animation_code"] = concept_html
    result["to_find"]                = to_find_targets
    result["given_cards"]            = given_cards
    result["haiku_solution"]         = haiku_sol
    result["glossary_terms"]         = glossary_result.get("terms", [])
    result.setdefault("solution_steps", [])
    result.setdefault("final_answer",   "")
    result.setdefault("key_insight",    "")

    # Prefer Haiku solution steps if more detailed
    haiku_steps = haiku_sol.get("steps", [])
    if haiku_steps and (not result["solution_steps"] or len(haiku_steps) > len(result["solution_steps"])):
        result["solution_steps"] = haiku_steps
        QAnimLogger.ok("Pipeline", f"Using Haiku solution steps ({len(haiku_steps)} steps)")

    # Validate and upgrade final_answer
    def _is_real_answer(s):
        return bool(s and len(str(s).strip()) > 5 and any(c.isdigit() for c in str(s)))

    if not _is_real_answer(result["final_answer"]) and _is_real_answer(haiku_sol.get("final_answer", "")):
        result["final_answer"] = haiku_sol["final_answer"]
        QAnimLogger.ok("Pipeline", "Used Haiku final_answer (solution AI returned empty/placeholder)")

    if not _is_real_answer(result["final_answer"]):
        raw_haiku = haiku_sol.get("raw", "").strip()
        if raw_haiku:
            _fa_match = re.search(
                r'(?:\*{0,2}Final Answer\*{0,2})\s*:\s*(.+?)(?:\*{0,2}Key Insight\*{0,2}|$)',
                raw_haiku, re.DOTALL | re.IGNORECASE)
            result["final_answer"] = _fa_match.group(1).strip() if _fa_match else raw_haiku[:300]
            QAnimLogger.warn("Pipeline", "final_answer extracted from Haiku raw text")
        else:
            result["final_answer"] = "Solution computed — see step-by-step for full details."
            QAnimLogger.warn("Pipeline", "final_answer was empty; used fallback message")

    if haiku_sol.get("key_insight") and not result["key_insight"]:
        result["key_insight"] = haiku_sol["key_insight"]

    if not result["key_insight"]:
        raw_haiku = haiku_sol.get("raw", "").strip()
        if raw_haiku:
            _ki_match = re.search(
                r'\*{0,2}Key Insight\*{0,2}\s*:\s*(.+?)$',
                raw_haiku, re.DOTALL | re.IGNORECASE)
            if _ki_match:
                result["key_insight"] = _ki_match.group(1).strip().lstrip('*').rstrip('*').strip()
                QAnimLogger.warn("Pipeline", "key_insight extracted from Haiku raw text")

    if not result["key_insight"]:
        result["key_insight"] = (
            "Focus on the core concept behind this problem -- spotting it "
            "quickly is what makes similar questions easier next time."
        )
        QAnimLogger.warn("Pipeline", "key_insight was empty; used fallback message")

    # ── v0.2 PAGE LAYOUT BUILD ──
    # Build the full standalone page HTML with proper layout
    raw_html = result.get("animation_code", "")

    # Sanitize the raw AI HTML first (for the SVG extraction)
    raw_html = HtmlSanitizer.sanitize(raw_html)

    # Build full page layout
    try:
        page_html, scene_descs = build_page_html(question, result, given_cards, category, n_scenes)
    except Exception as e:
        QAnimLogger.error("PageBuilder", f"build_page_html failed: {e}")
        page_html = RecoveryEngine.fallback_html(question, f"Page build error: {e}")
        scene_descs = []

    # ── [Gemini] Inject Scene 0 into the built page ─────────────────────────
    # Gemini is the PRIMARY generator for scene 0. Claude was told to embed
    # Gemini's SVG verbatim in its output (or a stub if Gemini failed).
    # We now ensure Gemini's animateScene0() JS is also spliced in correctly.
    if gemini_scene0_group and gemini_animate0_fn:
        QAnimLogger.info("Merging", "Splicing Gemini Scene 1 into page HTML...")
        try:
            # Extract current SVG + script from page_html, splice, then put back.
            _cur_svg, _cur_script = _extract_svg_from_html(page_html)
            _new_svg, _new_script = _splice_gemini_scene0_into_svg(
                _cur_svg, _cur_script, gemini_scene0_group, gemini_animate0_fn
            )
            if _new_svg != _cur_svg or _new_script != _cur_script:
                # Replace old SVG block in page_html
                if _cur_svg:
                    page_html = page_html.replace(_cur_svg, _new_svg, 1)
                # Replace old anim_script in page_html (strip wrapper tags for matching)
                if _cur_script and _new_script != _cur_script:
                    page_html = page_html.replace(_cur_script, _new_script, 1)
                QAnimLogger.ok("Merging", "Gemini Scene 1 spliced successfully.")
            else:
                QAnimLogger.warn("Merging", "Splice produced no changes -- Gemini Scene 1 not applied")
        except Exception as _splice_err:
            QAnimLogger.error("Merging", f"Splice failed: {_splice_err} -- using Claude's scene-0")
    else:
        QAnimLogger.info("Merging", "No Gemini scene-0 content -- using Claude's scene-0 (fallback)")

    # ── SAFETY NET: Detect and fix empty animateScene0() in final page HTML ──
    # This catches the case where Claude generated an empty stub AND Gemini
    # splice did not run or failed -- which causes "Loading scene..." in browser.
    _empty_s0_pattern = re.compile(
        r'function\s+animateScene0\s*\(\s*\)\s*\{[^}]{0,120}\}',
        re.DOTALL
    )
    _s0_match = _empty_s0_pattern.search(page_html)
    if _s0_match:
        _s0_body = _s0_match.group(0)
        # Consider it empty if it has no getElementById calls at all
        if 'getElementById' not in _s0_body and 'fadeIn' not in _s0_body:
            QAnimLogger.warn("Scene0Fix", "Detected empty animateScene0() -- injecting fallback animation")
            # Extract all IDs from scene-0 SVG group to build a real fadeIn sequence
            _scene0_ids = re.findall(
                r'<(?:text|rect|circle|path|line|ellipse|polygon|image)[^>]+id=["\']([^"\']+)["\']',
                page_html
            )
            # Only keep IDs that look like scene-0 elements (s0- prefix or first ~15 ids)
            _s0_ids = [i for i in _scene0_ids if i.startswith('s0-')]
            if not _s0_ids:
                _s0_ids = _scene0_ids[:15]  # fallback: first 15 element IDs
            if _s0_ids:
                _id_list = "','".join(_s0_ids)
                _fallback_fn = (
                    "function animateScene0(){"
                    f"var ids=['{_id_list}'];"
                    "for(var i=0;i<ids.length;i++){"
                    "(function(id,delay){setTimeout(function(){"
                    "var el=document.getElementById(id);"
                    "if(el)el.setAttribute('opacity','1');"
                    "},delay);})(ids[i],150+i*130);"
                    "}"
                    "}"
                )
                page_html = page_html.replace(_s0_body, _fallback_fn, 1)
                QAnimLogger.ok("Scene0Fix", f"Injected fallback animateScene0() with {len(_s0_ids)} element IDs")
            else:
                QAnimLogger.warn("Scene0Fix", "No scene-0 element IDs found -- cannot inject fallback")

    QAnimLogger.info("Pipeline", "Completed successfully.")

    # Validate the base page structure
    try:
        GenerationValidator.validate(page_html, require_svg=True)
    except ValidationError as e:
        QAnimLogger.warn("Validator", f"Page validation: {e}")

    # ── Build answer targets ──
    answer_targets = _build_answer_targets(
        to_find_targets=to_find_targets,
        haiku_sol=haiku_sol,
        final_answer=result["final_answer"],
        key_insight=result["key_insight"],
    )
    result["answer_targets"] = answer_targets
    QAnimLogger.info("Pipeline", f"Answer targets: {len(answer_targets)}")

    # ── Inject all panels and scripts in correct order ──
    html = page_html
    html = inject_final_answer_panel(
        html=html,
        answer_targets=answer_targets,
        final_answer=result["final_answer"],
        key_insight=result["key_insight"],
    )
    html = inject_to_find_system(html, to_find_targets)
    html = inject_notes_system(html)
    html = inject_answer_box_panel(html, answer_targets)
    html = inject_controls_bar(html)
    html = inject_glossary_panel(html, result.get("glossary_terms", []))  # NEW in v0.6
    html = inject_teacher_voice(html)
    html = inject_nav_patch_and_scene_desc(html, scene_descs)  # NEW in v0.2
    html = inject_step_controller(html)   # MUST be absolute last

    # Final validation (warn only)
    try:
        GenerationValidator.validate(html, require_svg=True)
    except ValidationError as e:
        QAnimLogger.warn("FinalValidator", f"Post-injection: {e} -- continuing")

    result["animation_code"] = html
    result["render_status"]  = "ok"

    QAnimLogger.ok("Pipeline", (
        f"DONE v0.2 -- '{result['title']}' "
        f"concept={len(concept_html):,} "
        f"solution={len(html):,} "
        f"haiku_steps={len(haiku_steps)} "
        f"to_find={result['to_find']} "
        f"given_cards={len(given_cards)} "
        f"answer_targets={len(answer_targets)} "
        f"simple_method={simple_result.get('method_name') or 'none'}"
    ))
    return result


